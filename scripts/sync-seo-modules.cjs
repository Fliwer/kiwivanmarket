// React uses ESM. Server functions use generated CommonJS copies of the same
// source, so stock rules and translations cannot diverge at deployment time.
const fs = require('node:fs');
const path = require('node:path');
for (const name of ['copy', 'market', 'taxonomy', 'long-tail', 'search-copy', 'inventory']) {
  const root = path.join(__dirname, '..', 'src', 'data', 'seo');
  const source = fs.readFileSync(path.join(root, `${name}.js`), 'utf8');
  const generated = '// Generated by scripts/sync-seo-modules.cjs; edit the .js source.\n'
    + source.replace(/^import (\w+) from '\.\/([\w-]+)';$/gm,
      "const $1 = require('./$2.cjs');")
      .replace('export default', 'module.exports =');
  const target = path.join(root, `${name}.cjs`);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== generated) {
      throw new Error(`SEO source and server module differ: ${name}`);
    }
  } else fs.writeFileSync(target, generated);
}
